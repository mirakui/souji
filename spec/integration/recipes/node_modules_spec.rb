# frozen_string_literal: true

require "fileutils"
require "souji/recipes/node_modules"

RSpec.describe Souji::Recipes::NodeModules do
  let(:recipe) { described_class.new }

  describe "class-level declarations" do
    it "registers under 'node-modules'" do
      expect(described_class.recipe_name).to eq("node-modules")
    end

    it "declares no required external commands (pure filesystem)" do
      expect(described_class.required_external_commands).to eq([])
    end

    it "declares only older_than_days" do
      expect(described_class.param_names).to eq([:older_than_days])
    end
  end

  describe "#enumerate" do
    it "proposes the node_modules of a project with a manifest and a lockfile" do
      with_tmp_dir do |tmp|
        project = make_node_project(File.join(tmp, "app"))

        items = recipe.enumerate([tmp], {})

        expect(items.map(&:path)).to eq([File.join(project, "node_modules")])
        expect(items.first.metadata).to include(
          "project" => project, "lockfile" => "pnpm-lock.yaml", "package_manager" => "pnpm",
          "install_signal" => ".modules.yaml"
        )
        expect(items.first.size_bytes).to be > 0
      end
    end

    it "skips a workspace root that has a lockfile but no package.json" do
      with_tmp_dir do |tmp|
        # The real-world shape this exists for: a pnpm workspace root whose
        # packages live elsewhere. Without a manifest the reinstall cannot
        # be reproduced, so souji must not touch it.
        make_node_project(File.join(tmp, "workspace"), package_json: :none)

        expect(recipe.enumerate([tmp], {})).to eq([])
      end
    end

    it "survives a package.json whose scripts is not an object" do
      with_tmp_dir do |tmp|
        # `dig` raises TypeError on a String or an Array here, and nothing
        # between this and PlanCommand rescues it -- one malformed manifest
        # would abort the whole plan for every recipe.
        project = make_node_project(File.join(tmp, "app"))
        ['{"scripts":"nope"}', '{"scripts":[]}', '{"scripts":null}'].each do |body|
          File.write(File.join(project, "package.json"), body)

          items = recipe.enumerate([tmp], {})

          expect(items.size).to eq(1)
          expect(items.first.metadata).not_to have_key("has_postinstall")
        end
      end
    end

    it "skips a project whose package.json does not parse" do
      with_tmp_dir do |tmp|
        project = make_node_project(File.join(tmp, "app"))
        File.write(File.join(project, "package.json"), "{ this is not json")

        expect(recipe.enumerate([tmp], {})).to eq([])
      end
    end

    it "skips a project with no lockfile, because a reinstall would re-resolve semver ranges" do
      with_tmp_dir do |tmp|
        make_node_project(File.join(tmp, "app"), lockfile: nil)

        expect(recipe.enumerate([tmp], {})).to eq([])
      end
    end

    it "names the package manager from the lockfile it found" do
      with_tmp_dir do |tmp|
        make_node_project(File.join(tmp, "npm-app"), lockfile: "package-lock.json",
                                                     receipt: ".package-lock.json")
        make_node_project(File.join(tmp, "yarn-app"), lockfile: "yarn.lock", receipt: ".yarn-integrity")
        make_node_project(File.join(tmp, "bun-app"), lockfile: "bun.lock", receipt: nil)

        managers = recipe.enumerate([tmp], {}).to_h { |i| [File.basename(i.metadata["project"]), i] }

        expect(managers["npm-app"].metadata["package_manager"]).to eq("npm")
        expect(managers["yarn-app"].metadata["package_manager"]).to eq("yarn")
        expect(managers["bun-app"].metadata["package_manager"]).to eq("bun")
      end
    end

    it "prefers package.json's own packageManager field as the human-facing label" do
      with_tmp_dir do |tmp|
        make_node_project(File.join(tmp, "app"), package_json: { "packageManager" => "pnpm@10.15.1" })

        expect(recipe.enumerate([tmp], {}).first.metadata["package_manager_declared"]).to eq("pnpm@10.15.1")
      end
    end

    it "records a postinstall script without letting it disqualify the project" do
      with_tmp_dir do |tmp|
        make_node_project(File.join(tmp, "app"),
                          package_json: { "scripts" => { "postinstall" => "node build.js" } })

        item = recipe.enumerate([tmp], {}).first

        expect(item.metadata["has_postinstall"]).to be true
        expect(item.reason).to match(/postinstall/)
      end
    end

    it "records a patches/ directory without letting it disqualify the project" do
      with_tmp_dir do |tmp|
        project = make_node_project(File.join(tmp, "app"))
        FileUtils.mkdir_p(File.join(project, "patches"))

        expect(recipe.enumerate([tmp], {}).first.metadata["has_patches"]).to be true
      end
    end

    it "never proposes a nested node_modules, because the walk prunes on the first one" do
      with_tmp_dir do |tmp|
        project = make_node_project(File.join(tmp, "app"), nested: true)

        expect(recipe.enumerate([tmp], {}).map(&:path)).to eq([File.join(project, "node_modules")])
      end
    end

    it "proposes only the workspace root in a monorepo, because the packages have no lockfile" do
      with_tmp_dir do |tmp|
        root = make_node_project(File.join(tmp, "monorepo"))
        make_node_project(File.join(root, "services", "api"), lockfile: nil)

        expect(recipe.enumerate([tmp], {}).map(&:path)).to eq([File.join(root, "node_modules")])
      end
    end

    it "does not follow a symlinked node_modules" do
      with_tmp_dir do |tmp|
        real = make_node_project(File.join(tmp, "real"))
        fake = File.join(tmp, "linked")
        FileUtils.mkdir_p(fake)
        File.write(File.join(fake, "package.json"), "{}")
        File.write(File.join(fake, "pnpm-lock.yaml"), "")
        File.symlink(File.join(real, "node_modules"), File.join(fake, "node_modules"))

        expect(recipe.enumerate([tmp], {}).map { |i| i.metadata["project"] }).to eq([real])
      end
    end

    it "returns the same items in the same order across runs" do
      with_tmp_dir do |tmp|
        %w[b a c].each { |name| make_node_project(File.join(tmp, name)) }

        expect(recipe.enumerate([tmp], {}).map(&:path)).to eq(recipe.enumerate([tmp], {}).map(&:path))
      end
    end

    describe "with older_than_days:" do
      it "proposes a project whose install receipt is old enough" do
        with_tmp_dir do |tmp|
          project = make_node_project(File.join(tmp, "app"))
          backdate_node_install(project, days: 143)

          item = recipe.enumerate([tmp], older_than_days: 90).first

          expect(item.metadata["older_than_days"]).to eq(90)
          expect(item.reason).to match(/last pnpm install 143 days ago/)
        end
      end

      it "keeps a project that was installed recently" do
        with_tmp_dir do |tmp|
          make_node_project(File.join(tmp, "app"))

          expect(recipe.enumerate([tmp], older_than_days: 90)).to eq([])
        end
      end

      it "measures the install, not the lockfile: a fresh install from an old lockfile is kept" do
        with_tmp_dir do |tmp|
          # A lockfile untouched for a year says the dependencies have not
          # changed, not that nobody has installed them.
          project = make_node_project(File.join(tmp, "app"))
          backdate(File.join(project, "pnpm-lock.yaml"), days: 400)

          expect(recipe.enumerate([tmp], older_than_days: 90)).to eq([])
        end
      end

      it "measures the install, not project source activity" do
        with_tmp_dir do |tmp|
          project = make_node_project(File.join(tmp, "app"))
          backdate_node_install(project, days: 300)
          File.write(File.join(project, "index.js"), "// edited just now\n")

          expect(recipe.enumerate([tmp], older_than_days: 90).size).to eq(1)
        end
      end
    end
  end

  describe "#verify" do
    it "accepts an item whose project is unchanged" do
      with_tmp_dir do |tmp|
        make_node_project(File.join(tmp, "app"))

        expect(recipe.verify(recipe.enumerate([tmp], {}).first)).to eq(:ok)
      end
    end

    it "skips a tree that is already gone" do
      with_tmp_dir do |tmp|
        make_node_project(File.join(tmp, "app"))
        item = recipe.enumerate([tmp], {}).first
        FileUtils.remove_entry(item.path)

        expect(recipe.verify(item)).to eq([:skip, "already removed"])
      end
    end

    it "skips once package.json is gone" do
      with_tmp_dir do |tmp|
        project = make_node_project(File.join(tmp, "app"))
        item = recipe.enumerate([tmp], {}).first
        FileUtils.rm_f(File.join(project, "package.json"))

        expect(recipe.verify(item).last).to match(/package\.json/)
      end
    end

    it "skips once the lockfile is gone" do
      with_tmp_dir do |tmp|
        project = make_node_project(File.join(tmp, "app"))
        item = recipe.enumerate([tmp], {}).first
        FileUtils.rm_f(File.join(project, "pnpm-lock.yaml"))

        expect(recipe.verify(item).last).to match(/lockfile/)
      end
    end

    it "cannot be repointed at the project's own source by a hand-edited plan" do
      with_tmp_dir do |tmp|
        project = make_node_project(File.join(tmp, "app"))
        FileUtils.mkdir_p(File.join(project, "src"))
        item = recipe.enumerate([tmp], {}).first
        tampered = Souji::PlanItem.new(id: item.id, recipe: item.recipe,
                                       path: File.join(project, "src"),
                                       reason: item.reason, size_bytes: nil,
                                       metadata: item.metadata)

        expect(recipe.verify(tampered)).to eq([:skip, "not a node_modules directory"])
      end
    end

    it "skips when the project was reinstalled between plan and apply" do
      with_tmp_dir do |tmp|
        project = make_node_project(File.join(tmp, "app"))
        backdate_node_install(project, days: 200)
        item = recipe.enumerate([tmp], older_than_days: 90).first

        now = Time.now
        File.utime(now, now, File.join(project, "node_modules", ".modules.yaml"))

        expect(recipe.verify(item).last).to match(/reinstalled 0 days ago/)
      end
    end
  end

  describe "#delete" do
    it "disposes of the tree and reports the outcome" do
      with_tmp_dir do |tmp|
        make_node_project(File.join(tmp, "app"))
        item = recipe.enumerate([tmp], {}).first

        expect(%i[trashed deleted]).to include(recipe.delete(item))
      end
    end
  end
end
