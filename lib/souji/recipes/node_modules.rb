# frozen_string_literal: true

require "time"
require_relative "../recipe"
require_relative "../plan_item"
require_relative "../trash"
require_relative "../fs_scan"
require_relative "../node/project"

module Souji
  module Recipes
    # Reclaims `node_modules/` trees a lockfiled install can rebuild.
    #
    # Only proposed when the project carries both the manifest and the
    # lockfile that make the reinstall reproducible -- see
    # `Souji::Node::Project#blocker`. Two useful properties fall out of
    # that rule rather than being special-cased: a pnpm workspace root
    # whose packages live elsewhere is never proposed, and in a monorepo
    # only the root holding the lockfile is, because the package-level
    # trees have no lockfile of their own.
    #
    # Nested `node_modules` are unreachable by construction: the walk
    # prunes on the first one it finds, so `node_modules/.pnpm/**/node_modules`
    # is never visited and no path-substring heuristic is needed.
    class NodeModules < Souji::Recipe
      recipe_name "node-modules"
      description "Remove stale node_modules/ directories that a lockfiled install can rebuild"
      param :older_than_days,
            "Only propose node_modules whose last install is at least this many days old " \
            "(default: no age filter)"

      WALK_SKIP_DIRS = (Souji::FsScan::SKIP_DIR_NAMES - [Souji::Node::Project::MODULES_DIR]).freeze

      def enumerate(target_roots, params)
        older_than_days = params[:older_than_days]
        target_roots.flat_map { |target| scan(target, older_than_days) }
      end

      # Derived from `plan_item.path`, never from the metadata beside it:
      # nothing ties the two together, so a hand-edited plan pointing at a
      # project's source directory while leaving the metadata intact would
      # otherwise pass every guard.
      def verify(plan_item)
        path = File.expand_path(plan_item.path)
        return [:skip, "already removed"] unless Dir.exist?(path)
        return [:skip, "path is now a symlink"] if File.symlink?(path)

        unless File.basename(path) == Souji::Node::Project::MODULES_DIR
          return [:skip, "not a #{Souji::Node::Project::MODULES_DIR} directory"]
        end

        recheck(Souji::Node::Project.new(File.dirname(path)), plan_item.metadata["older_than_days"])
      end

      def delete(plan_item)
        Souji::Trash.dispose(plan_item.path)
      rescue StandardError => e
        [:failed, e.message]
      end

      private

      def scan(target, older_than_days)
        items = []
        Souji::FsScan.walk_dirs(target, skip: WALK_SKIP_DIRS) do |dir|
          next unless File.basename(dir) == Souji::Node::Project::MODULES_DIR

          item = assess(File.dirname(dir), older_than_days)
          items << item if item
          :prune
        end
        items
      end

      def assess(path, older_than_days)
        progress.scanning(path)
        project = Souji::Node::Project.new(path)
        reason = recheck(project, older_than_days)
        return build_item(project, older_than_days) if reason == :ok

        progress.note("keeping #{project.modules_dir}: #{reason.last}")
        nil
      end

      # The single judgement, shared by plan and apply so the two cannot
      # drift.
      def recheck(project, older_than_days)
        blocker = project.blocker
        return [:skip, blocker] if blocker

        age_skip(project, older_than_days) || :ok
      end

      def age_skip(project, older_than_days)
        _signal, at = project.install
        case (verdict = Souji::FsScan.staleness(at, older_than_days))
        when :stale then nil
        when :unknown then [:skip, "cannot tell when it was last installed"]
        else [:skip, "reinstalled #{Souji::FsScan.days_phrase(verdict.last)} ago"]
        end
      end

      def build_item(project, older_than_days)
        signal, install_at = project.install
        project_at, truncated = Souji::FsScan.newest_mtime_under(project.path)
        Souji::PlanItem.new(
          id: Souji::PlanItem.generate_id("node-modules"),
          recipe: "node-modules",
          path: project.modules_dir,
          reason: reason_for(project, install_at),
          size_bytes: Souji::FsScan.dir_size(project.modules_dir),
          metadata: metadata_for(project, signal, install_at, older_than_days)
                    .merge("project_at" => iso8601(project_at),
                           "project_at_truncated" => (true if truncated))
                    .compact
        )
      end

      def metadata_for(project, signal, install_at, older_than_days)
        {
          "project" => project.path,
          "package_json" => project.package_json,
          "lockfile" => project.lockfile,
          "package_manager" => project.package_manager,
          "package_manager_declared" => project.declared_package_manager,
          "install_at" => iso8601(install_at),
          "install_signal" => signal,
          "older_than_days" => older_than_days,
          "lockfile_at" => iso8601(project.lockfile_at),
          "has_postinstall" => (true if project.postinstall?),
          "has_patches" => (true if project.patches?)
        }
      end

      def reason_for(project, install_at)
        days = Souji::FsScan.days_since(install_at)
        age = if days
                "last #{project.package_manager} install #{Souji::FsScan.days_phrase(days)} ago"
              else
                "last install unknown"
              end
        caveat = ", and reinstalling runs a postinstall script" if project.postinstall?
        "Stale node_modules (#{age}); #{project.lockfile} can rebuild it#{caveat}"
      end

      def iso8601(time)
        time&.utc&.iso8601
      end
    end
  end
end
